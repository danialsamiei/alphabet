#!/usr/bin/env node
/**
 * @file apps/docs/scripts/sync-docs.mjs
 * @description
 * Mirror the canonical Markdown files under the monorepo's `docs/` directory
 * into `apps/docs/pages/docs/` as MDX so Nextra picks them up as pages.
 *
 * Why mirroring instead of in-place imports:
 *   * Nextra discovers pages by walking `pages/` at build time. It does not
 *     follow symlinks reliably across platforms (Windows in particular).
 *   * Plain copying of `.md` -> `.mdx` lets Nextra apply MDX features
 *     (admonitions, syntax highlighting, copy-code) without forking content.
 *   * We never edit the mirrored copies; `docs/*.md` is the single source of
 *     truth. The mirror is regenerated on every `predev` and `prebuild`.
 *   * The mirror directory is gitignored so it never drifts from source.
 *
 * Sidebar order is controlled by `_meta.json` files which we generate from
 * the curated `IA` array below — this is the only place we hand-author IA;
 * everything else is content-driven.
 */

import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  rmSync,
  readdirSync,
  existsSync,
} from 'node:fs';
import { resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = resolve(HERE, '..');
const REPO_ROOT = resolve(APP_ROOT, '..', '..');
const SRC_DIR = resolve(REPO_ROOT, 'docs');
const DEST_DIR = resolve(APP_ROOT, 'pages', 'docs');

/**
 * Information architecture mirroring AGENTS.md "8-layer architecture".
 * Each row is `[ slug, sourceFileBasename, displayTitle ]`. The display
 * title is what shows in the sidebar — slug is the URL segment.
 *
 * If a source file is missing, we render a stub page rather than fail —
 * this keeps the docs build green even when a doc has not been written yet.
 */
const IA = [
  // Overview & getting started
  ['overview', 'ARCHITECTURE.md', 'Architecture overview'],
  ['quickstart', 'DEVELOPMENT.md', 'Quickstart'],
  ['examples', 'EXAMPLES.md', 'Examples'],

  // Concepts (mirrors AGENTS.md "Core Concepts Every Agent Must Know")
  ['concepts/core', 'CORE_CONCEPTS.md', 'Core concepts'],
  ['concepts/handshake', 'API_CONTRACT.md', 'Context handshake'],
  ['concepts/render-layers', 'ADAPTIVE_RENDER_LAYERS.md', 'Adaptive render layers'],
  ['concepts/protocols', 'PROTOCOLS.md', 'Protocols'],
  ['concepts/protocols-v2', 'PROTOCOL_V2.md', 'Protocols v2 (proactive)'],
  ['concepts/integrations', 'INTEGRATIONS.md', 'Integrations'],

  // Reference
  ['reference/api', 'API_REFERENCE.md', 'API reference'],
  ['reference/coding-conventions', 'CODING_CONVENTIONS.md', 'Coding conventions'],
  ['reference/performance', 'PERFORMANCE.md', 'Performance'],

  // Privacy & Security
  ['security/security', 'SECURITY.md', 'Security'],
  ['security/security-model', 'SECURITY_MODEL.md', 'Security model'],
  ['security/privacy-model', 'PRIVACY_MODEL.md', 'Privacy model'],
  ['security/launch-review', 'LAUNCH_SECURITY_REVIEW.md', 'Launch security review'],

  // Roadmap & operations
  ['roadmap', 'ROADMAP.md', 'Roadmap'],
  ['release', 'RELEASE.md', 'Release process'],
  ['production-checklist', 'PRODUCTION_RELEASE_CHECKLIST.md', 'Production release checklist'],
  ['launch-checklist', 'LAUNCH_CHECKLIST.md', 'Launch checklist'],
  ['launch-narrative', 'LAUNCH_NARRATIVE.md', 'Launch narrative'],
  ['implementation-status', 'IMPLEMENTATION_STATUS.md', 'Implementation status'],
  ['contributing', 'CONTRIBUTING.md', 'Contributing'],
];

/**
 * Convert a piece of plain markdown into an MDX module body. We escape the
 * content into a fenced template literal? No — that breaks copy-code and
 * heading anchors. Instead we:
 *   1. Strip leading YAML frontmatter (Nextra prefers its own).
 *   2. Prepend our own minimal frontmatter with the page title.
 *   3. Pass the rest through verbatim.
 *
 * @param {string} markdown
 * @param {string} title
 * @param {string} sourceRelative — the path relative to repo root, used for the "edit" link.
 */
function toMdx(markdown, title, sourceRelative) {
  // Strip YAML frontmatter if present.
  const withoutFrontmatter = markdown.replace(/^---[\s\S]*?\n---\s*\n/, '');
  // The "Source" line at the bottom links back to the canonical file so a
  // reader who finds something wrong on the docs site can edit the source.
  const sourceFooter =
    `\n\n---\n\n*Source: [\`${sourceRelative}\`](https://github.com/danialsamiei/alphabet/blob/main/${sourceRelative})*\n`;
  return [
    '---',
    `title: ${JSON.stringify(title)}`,
    '---',
    '',
    `{/* This file is auto-generated by apps/docs/scripts/sync-docs.mjs from ${sourceRelative}. Do not edit. */}`,
    '',
    withoutFrontmatter.trim(),
    sourceFooter,
  ].join('\n');
}

/**
 * @param {string} slug
 * @param {string} title
 */
function stubMdx(slug, title) {
  return `---
title: ${JSON.stringify(title)}
---

{/* This file is auto-generated by apps/docs/scripts/sync-docs.mjs. */}

# ${title}

This page is a placeholder. The canonical document for \`${slug}\` is not
yet present in the repository's \`docs/\` directory. When it lands,
\`apps/docs/scripts/sync-docs.mjs\` will mirror it into this slot
automatically — no edits required here.
`;
}

// ---------------------------------------------------------------------------
// Build the mirror.
// ---------------------------------------------------------------------------

if (existsSync(DEST_DIR)) rmSync(DEST_DIR, { recursive: true, force: true });
mkdirSync(DEST_DIR, { recursive: true });

/** @type {Map<string, Array<[string, string]>>} */
const sectionMeta = new Map();
sectionMeta.set('', []); // top-level meta

for (const [slug, srcName, title] of IA) {
  const slugParts = slug.split('/');
  const fileName = `${slugParts[slugParts.length - 1]}.mdx`;
  const sectionDir = slugParts.slice(0, -1).join('/');
  const destDir = sectionDir ? resolve(DEST_DIR, sectionDir) : DEST_DIR;
  mkdirSync(destDir, { recursive: true });
  const destFile = resolve(destDir, fileName);

  const srcPath = resolve(SRC_DIR, srcName);
  if (existsSync(srcPath)) {
    const md = readFileSync(srcPath, 'utf8');
    writeFileSync(destFile, toMdx(md, title, `docs/${srcName}`));
  } else {
    writeFileSync(destFile, stubMdx(slug, title));
  }

  // Record sidebar order.
  const slotKey = sectionDir;
  if (!sectionMeta.has(slotKey)) sectionMeta.set(slotKey, []);
  sectionMeta.get(slotKey).push([slugParts[slugParts.length - 1], title]);
}

// `_meta.json` files drive Nextra's sidebar order + display titles.
for (const [section, entries] of sectionMeta) {
  /** @type {Record<string, string>} */
  const meta = {};
  for (const [slug, title] of entries) meta[slug] = title;
  const metaDir = section ? resolve(DEST_DIR, section) : DEST_DIR;
  writeFileSync(resolve(metaDir, '_meta.json'), JSON.stringify(meta, null, 2));
}

// Section index page meta (for parents like `concepts`, `reference`,
// `security`) — display name + collapsed-by-default state. Without these,
// Nextra renders raw slugs in the sidebar.
const sectionIndex = {
  concepts: 'Concepts',
  reference: 'Reference',
  security: 'Privacy & Security',
};
const topMetaPath = resolve(DEST_DIR, '_meta.json');
const topMetaRaw = JSON.parse(readFileSync(topMetaPath, 'utf8'));
const topMeta = {};
// Curated order at the top level.
const order = [
  'overview',
  'quickstart',
  'examples',
  'concepts',
  'reference',
  'security',
  'roadmap',
  'release',
  'production-checklist',
  'launch-checklist',
  'launch-narrative',
  'implementation-status',
  'contributing',
];
for (const key of order) {
  if (sectionIndex[key]) topMeta[key] = sectionIndex[key];
  else if (topMetaRaw[key]) topMeta[key] = topMetaRaw[key];
}
writeFileSync(topMetaPath, JSON.stringify(topMeta, null, 2));

console.log(`Synced ${IA.length} doc page(s) into ${DEST_DIR}`);
