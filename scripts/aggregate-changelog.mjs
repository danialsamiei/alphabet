#!/usr/bin/env node
/**
 * @file scripts/aggregate-changelog.mjs
 * @description
 * Regenerates the top-level `CHANGELOG.md` by aggregating per-package
 * CHANGELOG.md files (one per directory under `packages/`) emitted by Changesets.
 *
 * Convention:
 *   - Per-package CHANGELOGs use the standard Changesets "## <version>" headers
 *     emitted by `@changesets/cli/changelog`.
 *   - The aggregated file lists each version that has appeared in any package,
 *     newest first, with one section per package that shipped in that version.
 *
 * This script is intentionally read-only against per-package files; it never
 * mutates them. It writes only the top-level `CHANGELOG.md`.
 *
 * Run:    `node scripts/aggregate-changelog.mjs`
 * Output: `CHANGELOG.md` at the repository root.
 *
 * Used by `.github/workflows/changelog.yml` after every release tag push.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGES_DIR = resolve(ROOT, 'packages');

/**
 * Parse a Changesets-style CHANGELOG.md into version sections.
 *
 * Returns a map keyed by version string (e.g. "1.0.0") whose value is the
 * raw markdown body that follows the `## <version>` heading, up to (but not
 * including) the next `## ` heading.
 *
 * @param {string} content
 * @returns {Map<string, string>}
 */
function parseChangelog(content) {
  /** @type {Map<string, string>} */
  const out = new Map();
  // Version sections look like `## 1.0.0` (Changesets default). Patch headings
  // can be `### Patch Changes`, `### Minor Changes`, `### Major Changes` —
  // those stay inside the section body.
  const lines = content.split(/\r?\n/);
  let currentVersion = null;
  /** @type {string[]} */
  let buffer = [];
  for (const line of lines) {
    const m = /^##\s+([0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?)\s*$/.exec(line);
    if (m) {
      if (currentVersion) out.set(currentVersion, buffer.join('\n').trim());
      currentVersion = m[1];
      buffer = [];
      continue;
    }
    if (currentVersion) buffer.push(line);
  }
  if (currentVersion) out.set(currentVersion, buffer.join('\n').trim());
  return out;
}

/**
 * Compare two semver-like strings, descending (newest first).
 * Pre-release tags sort lower than the corresponding release.
 * @param {string} a
 * @param {string} b
 */
function semverCmpDesc(a, b) {
  const pa = a.split('-');
  const pb = b.split('-');
  const av = pa[0].split('.').map((n) => Number.parseInt(n, 10));
  const bv = pb[0].split('.').map((n) => Number.parseInt(n, 10));
  for (let i = 0; i < 3; i += 1) {
    if ((av[i] ?? 0) !== (bv[i] ?? 0)) return (bv[i] ?? 0) - (av[i] ?? 0);
  }
  // Same MAJOR.MINOR.PATCH — release > pre-release.
  if (!pa[1] && pb[1]) return -1;
  if (pa[1] && !pb[1]) return 1;
  return (pb[1] ?? '').localeCompare(pa[1] ?? '');
}

const packages = readdirSync(PACKAGES_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name);

/** @type {Map<string, Map<string, string>>}  version -> packageName -> body */
const versionMap = new Map();

for (const pkg of packages) {
  const changelogPath = join(PACKAGES_DIR, pkg, 'CHANGELOG.md');
  if (!existsSync(changelogPath)) continue;
  const pkgJsonPath = join(PACKAGES_DIR, pkg, 'package.json');
  let pkgName = pkg;
  try {
    pkgName = JSON.parse(readFileSync(pkgJsonPath, 'utf8')).name ?? pkg;
  } catch {
    /* tolerate missing/invalid package.json */
  }
  const sections = parseChangelog(readFileSync(changelogPath, 'utf8'));
  for (const [version, body] of sections) {
    if (!versionMap.has(version)) versionMap.set(version, new Map());
    versionMap.get(version).set(pkgName, body);
  }
}

const versions = [...versionMap.keys()].sort(semverCmpDesc);

const lines = [
  '# Alphabet — Aggregated changelog',
  '',
  '> This file is generated by `scripts/aggregate-changelog.mjs` from the',
  "> per-package `CHANGELOG.md` files emitted by Changesets. Do not edit by hand —",
  '> per-package CHANGELOGs are the source of truth.',
  '',
];

if (versions.length === 0) {
  lines.push('_No releases yet. Per-package `CHANGELOG.md` files will be aggregated here on the first release._');
} else {
  for (const version of versions) {
    lines.push(`## ${version}`);
    lines.push('');
    const pkgs = [...versionMap.get(version).keys()].sort();
    for (const pkgName of pkgs) {
      const body = versionMap.get(version).get(pkgName).trim();
      lines.push(`### ${pkgName}`);
      lines.push('');
      lines.push(body.length > 0 ? body : '_No notes._');
      lines.push('');
    }
  }
}

writeFileSync(resolve(ROOT, 'CHANGELOG.md'), lines.join('\n').replace(/\n{3,}/g, '\n\n'));
console.log(`Wrote CHANGELOG.md (${versions.length} version(s) across ${packages.length} package(s)).`);
